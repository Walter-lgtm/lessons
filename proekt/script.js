var GOOGLE_FORM_CONFIG = {
  formUrl: 'https://docs.google.com/forms/d/REPLACE_FORM_ID/formResponse',
  fieldName: 'entry.REPLACE_NAME_FIELD_ID',
  fieldDirection: 'entry.REPLACE_DIRECTION_FIELD_ID'
};

function submitToGoogleForm(name, direction) {
  var formData = new FormData();
  formData.append(GOOGLE_FORM_CONFIG.fieldName, name);
  formData.append(GOOGLE_FORM_CONFIG.fieldDirection, direction);
  fetch(GOOGLE_FORM_CONFIG.formUrl, {
    method: 'POST',
    mode: 'no-cors',
    body: formData
  }).catch(function(e) { console.log('Отправка в Google Form (no-cors):', e); });
}

