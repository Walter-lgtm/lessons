let checklistProgress = 0;
function renderChecklist() {
  checklistProgress = 0;
  document.getElementById('checklist-content').innerHTML = `
    <div class="checklist-progress-container">
      <div class="checklist-progress-bar" id="checklist-bar" style="width:0%"></div>
      <span class="checklist-progress-text" id="checklist-text">0 / ${checklistItems.length} выполнено</span>
    </div>
    <div class="checklist-items">
      ${checklistItems.map((item, i) => `
        <label class="checklist-item">
          <input type="checkbox" onchange="updateChecklist()" data-idx="${i}">
          <span class="checklist-checkmark"></span>
          <span class="checklist-label">${item}</span>
        </label>
      `).join('')}
    </div>
  `;
}

function updateChecklist() {
  const checks = document.querySelectorAll('.checklist-item input[type="checkbox"]');
  let done = 0;
  checks.forEach(c => { if (c.checked) done++; });
  const pct = (done / checklistItems.length) * 100;
  document.getElementById('checklist-bar').style.width = pct + '%';
  document.getElementById('checklist-text').textContent = `${done} / ${checklistItems.length} выполнено`;
}

