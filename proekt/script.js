function toggleChecklist(index) {
    const item = document.getElementById(`check-${index}`);
    const checkbox = document.getElementById(`chk-${index}`);
    checkbox.checked = !checkbox.checked;
    item.classList.toggle('checked', checkbox.checked);
    updateChecklistProgress();
}

function updateChecklistProgress() {
    const checked = document.querySelectorAll('.checklist-item input[type="checkbox"]:checked').length;
    const total = checklistItems.length;
    document.getElementById('checklist-count').textContent = checked;
    document.getElementById('checklist-progress-fill').style.width = (checked / total * 100) + '%';
}

