var checklistState = {};

function toggleCheck(i) {
  var el = document.getElementById('check-' + i);
  if (!el) return;
  checklistState[i] = !checklistState[i];
  if (checklistState[i]) el.classList.add('done');
  else el.classList.remove('done');
  var box = el.querySelector('.checklist-box');
  if (box) box.innerHTML = checklistState[i] ? '\u2713' : '';
  updateChecklistProgress();
}

function updateChecklistProgress() {
  var done = 0;
  for (var i = 0; i < checklistItems.length; i++) {
    if (checklistState[i]) done++;
  }
  var pct = Math.round(done / checklistItems.length * 100);
  var bar = document.getElementById('checklist-progress');
  if (bar) {
    bar.style.width = pct + '%';
    bar.textContent = pct + '%';
  }
}

