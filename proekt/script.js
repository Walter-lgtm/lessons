let currentQuestion = 0;
let surveyAnswers = [];
let studentName = '';

function startSurvey() {
    const nameInput = document.getElementById('student-name');
    studentName = nameInput.value.trim();

    if (!studentName) {
        alert('Пожалуйста, укажите ваше ФИО!');
        return;
    }

    document.getElementById('survey-welcome').style.display = 'none';
    document.getElementById('survey-questions').style.display = 'block';
    currentQuestion = 0;
    surveyAnswers = [];
    renderQuestion();
}

function renderQuestion() {
    const q = surveyQuestions[currentQuestion];
    const total = surveyQuestions.length;

    document.getElementById('progress-fill').style.width = ((currentQuestion / total) * 100) + '%';
    document.getElementById('question-counter').textContent = `Вопрос ${currentQuestion + 1} из ${total}`;

    const area = document.getElementById('question-area');
    let optionsHtml = q.answers.map((a, i) => `
        <div class="answer-option ${surveyAnswers[currentQuestion] === i ? 'selected' : ''}" onclick="selectAnswer(${i})">
            <input type="radio" name="answer" id="ans-${i}" ${surveyAnswers[currentQuestion] === i ? 'checked' : ''}>
            <label for="ans-${i}">${a.text}</label>
        </div>
    `).join('');

    area.innerHTML = `
        <div class="question-text">${q.question}</div>
        <div class="answer-options">${optionsHtml}</div>
    `;

    document.getElementById('prev-btn').disabled = currentQuestion === 0;
    const nextBtn = document.getElementById('next-btn');
    if (currentQuestion === total - 1) {
        nextBtn.textContent = 'Завершить →';
    } else {
        nextBtn.textContent = 'Далее →';
    }
}

function selectAnswer(index) {
    surveyAnswers[currentQuestion] = index;
    renderQuestion();
}

function nextQuestion() {
    if (surveyAnswers[currentQuestion] === undefined) {
        alert('Пожалуйста, выберите ответ!');
        return;
    }

    if (currentQuestion < surveyQuestions.length - 1) {
        currentQuestion++;
        renderQuestion();
    } else {
        finishSurvey();
    }
}

function prevQuestion() {
    if (currentQuestion > 0) {
        currentQuestion--;
        renderQuestion();
    }
}

function finishSurvey() {
    // Подсчёт баллов
    let scores = { chemistry: 0, biology: 0, medicine: 0, engineering: 0, agrobiotech: 0 };

    surveyAnswers.forEach((ansIndex, qIndex) => {
        const ans = surveyQuestions[qIndex].answers[ansIndex];
        if (ans && ans.scores) {
            for (let dir in ans.scores) {
                scores[dir] += ans.scores[dir];
            }
        }
    });

    // Сортировка направлений по баллам
    const sorted = Object.entries(scores).sort((a, b) => b[1] - a[1]);
    const topDirection = sorted[0][0];
    const maxScore = sorted[0][1];

    // Отправка данных в Google Форму
    sendToGoogleForm(studentName, topDirection);

    // Формирование результатов
    document.getElementById('survey-questions').style.display = 'none';
    document.getElementById('survey-results').style.display = 'block';
    document.getElementById('progress-fill').style.width = '100%';

    let resultsHtml = `<p style="margin-bottom:20px; font-size:1.1em;">Ученик: <strong>${studentName}</strong></p>`;

    // Топ-2 направления
    sorted.slice(0, 2).forEach(([dir, score], i) => {
        const matchPercent = Math.round((score / maxScore) * 100);
        const topicIds = directionTopics[dir];
        const recommendedTopics = topicIds.map(id => {
            const t = topics.find(t => t.id === id);
            return `<li>Тема ${t.id}: ${t.title}</li>`;
        }).join('');

        resultsHtml += `
            <div class="result-card">
                <span class="match-score">${i === 0 ? 'Лучшее совпадение' : 'Запасной вариант'} · ${matchPercent}%</span>
                <h3>${directionNames[dir]}</h3>
                <p style="margin-bottom:10px;">Рекомендованные темы:</p>
                <ul>${recommendedTopics}</ul>
            </div>
        `;
    });

    resultsHtml += `
        <div class="info-block" style="margin-top:20px;">
            <h3>Распределение баллов по направлениям</h3>
            <ul>
                ${sorted.map(([dir, score]) => `<li>${directionNames[dir]}: ${score} баллов</li>`).join('')}
            </ul>
        </div>
    `;

    document.getElementById('results-content').innerHTML = resultsHtml;
}

function resetSurvey() {
    document.getElementById('survey-results').style.display = 'none';
    document.getElementById('survey-welcome').style.display = 'block';
    document.getElementById('student-name').value = '';
    studentName = '';
    surveyAnswers = [];
    currentQuestion = 0;
}

