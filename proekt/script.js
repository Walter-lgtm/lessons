function showTopicDetail(id) {
  const detail = document.getElementById(`topic-detail-${id}`);
  if (!detail) return;
  const topic = topics.find(t => t.id === id);
  if (!topic) return;

  const isShown = detail.style.display === 'block';
  detail.style.display = isShown ? 'none' : 'block';

  if (!isShown && !detail.innerHTML) {
    detail.innerHTML = `
      <h5 class="topic-plan-title">План работы:</h5>
      <table class="topic-plan-table">
        <thead><tr><th>Месяц</th><th>Задачи</th></tr></thead>
        <tbody>
          ${topic.plan.map(p => `
            <tr><td class="plan-month">${p[0]}</td><td>${p[1]}</td></tr>
          `).join('')}
        </tbody>
      </table>
    `;
  }
}

