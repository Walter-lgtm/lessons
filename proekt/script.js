let quizState = { currentQ: 0, scores: {chem:0, bio:0, med:0, eng:0, agro:0}, studentName: '' };

function showScreen(id) {
  document.querySelectorAll('.screen').forEach(s => s.classList.remove('active'));
  document.getElementById(id).classList.add('active');
  if (id === 'topics') renderTopics('all');
  if (id === 'sirius') renderSirius();
  if (id === 'calendar') renderCalendar();
  if (id === 'report') renderReport();
  if (id === 'resources') renderResources();
  if (id === 'checklist') renderChecklist();
}

function startQuiz() {
  quizState = { currentQ: 0, scores: {chem:0, bio:0, med:0, eng:0, agro:0}, studentName: '' };
  showScreen('quiz');
  document.getElementById('quiz-name-step').style.display = 'block';
  document.getElementById('quiz-questions-step').style.display = 'none';
  document.getElementById('quiz-result-step').style.display = 'none';
}

function startQuizQuestions() {
  const name = document.getElementById('quiz-name-input').value.trim();
  if (!name) { alert('Пожалуйста, введите ФИО'); return; }
  quizState.studentName = name;
  document.getElementById('quiz-name-step').style.display = 'none';
  document.getElementById('quiz-questions-step').style.display = 'block';
  renderQuestion();
}

function renderQuestion() {
  const q = quizQuestions[quizState.currentQ];
  const container = document.getElementById('quiz-questions-step');
  const progress = ((quizState.currentQ) / quizQuestions.length) * 100;
  container.innerHTML = `
    <div class="quiz-progress-bar"><div style="width:${progress}%"></div></div>
    <p class="quiz-counter">Вопрос ${quizState.currentQ + 1} из ${quizQuestions.length}</p>
    <h3 class="quiz-question">${q.q}</h3>
    <div class="quiz-options">
      ${q.options.map((opt, i) => `
        <button class="quiz-option-btn" onclick="answerQuiz(${i})">
          ${opt.text}
        </button>
      `).join('')}
    </div>
  `;
}

function answerQuiz(idx) {
  const opt = quizQuestions[quizState.currentQ].options[idx];
  for (const dir in opt.scores) {
    quizState.scores[dir] += opt.scores[dir];
  }
  quizState.currentQ++;
  if (quizState.currentQ < quizQuestions.length) {
    renderQuestion();
  } else {
    showQuizResult();
  }
}

function showQuizResult() {
  const sorted = Object.entries(quizState.scores).sort((a, b) => b[1] - a[1]);
  const total = sorted.reduce((sum, [_, s]) => sum + s, 0);
  const top1 = sorted[0];
  const top2 = sorted[1];
  const pct1 = Math.round((top1[1] / total) * 100);
  const pct2 = Math.round((top2[1] / total) * 100);
  const dir1 = directions[top1[0]];
  const dir2 = directions[top2[0]];

  const matchedTopics = topics.filter(t => t.dir === top1[0] || t.dir === top2[0]);

  document.getElementById('quiz-questions-step').style.display = 'none';
  document.getElementById('quiz-result-step').style.display = 'block';

  document.getElementById('quiz-result-step').innerHTML = `
    <h3 class="quiz-result-title">Результаты анкетирования</h3>
    <p class="quiz-result-name">Ученик: ${quizState.studentName}</p>
    <div class="quiz-results-grid">
      <div class="quiz-result-card" style="border-color:${dir1.color}">
        <span class="quiz-result-icon">${dir1.icon}</span>
        <h4 style="color:${dir1.color}">${dir1.name}</h4>
        <p class="quiz-result-pct">${pct1}% совпадение</p>
      </div>
      <div class="quiz-result-card" style="border-color:${dir2.color}">
        <span class="quiz-result-icon">${dir2.icon}</span>
        <h4 style="color:${dir2.color}">${dir2.name}</h4>
        <p class="quiz-result-pct">${pct2}% совпадение</p>
      </div>
    </div>
    <h4 class="quiz-topics-title">Рекомендованные темы:</h4>
    <div class="quiz-topics-list">
      ${matchedTopics.map(t => `
        <div class="quiz-topic-item" onclick="showTopicDetail(${t.id})">
          <span class="quiz-topic-dir" style="background:${directions[t.dir].color}">${directions[t.dir].icon} ${directions[t.dir].name}</span>
          <span class="quiz-topic-title">${t.title}</span>
        </div>
      `).join('')}
    </div>
    <button class="quiz-send-btn" onclick="sendToGoogleForm('${top1[0]}')">
      Отправить результаты руководителю
    </button>
    <button class="quiz-retry-btn" onclick="startQuiz()">Пройти заново</button>
    <div id="quiz-send-status"></div>
  `;
}

function sendToGoogleForm(directionKey) {
  const dirName = directions[directionKey].name;
  const formData = new FormData();
  formData.append(GOOGLE_FORM_CONFIG.fieldName, quizState.studentName);
  formData.append(GOOGLE_FORM_CONFIG.fieldDirection, dirName);

  fetch(GOOGLE_FORM_CONFIG.formUrl, {
    method: 'POST',
    body: formData,
    mode: 'no-cors'
  }).then(() => {
    document.getElementById('quiz-send-status').innerHTML =
      '<p class="send-success">✅ Результаты отправлены руководителю в Google Таблицу</p>';
  }).catch(() => {
    // Fallback: открыть форму в новом окне
    const fallbackUrl = GOOGLE_FORM_CONFIG.formUrl.replace('formResponse', 'viewform');
    document.getElementById('quiz-send-status').innerHTML =
      '<p class="send-error">⚠️ Не удалось отправить автоматически. ' +
      '<a href="' + fallbackUrl + '" target="_blank">Откройте форму вручную</a></p>';
  });
}

