var surveyState = { currentQ: 0, answers: [], scores: {}, name: '' };

function renderSurvey() {
  var container = document.getElementById('survey-container');
  if (!container) return;

  if (surveyState.currentQ === 0) {
    container.innerHTML =
      '<h3>Введите ваше ФИО</h3>' +
      '<input type="text" class="input-field" id="survey-name" placeholder="Фамилия Имя Отчество">' +
      '<button class="action-btn" onclick="startSurvey()">Начать анкетирование</button>';
    return;
  }

  if (surveyState.currentQ > surveyQuestions.length) {
    renderSurveyResult();
    return;
  }

  var q = surveyQuestions[surveyState.currentQ - 1];
  var progress = Math.round((surveyState.currentQ - 1) / surveyQuestions.length * 100);
  var optsHtml = '';
  q.options.forEach(function(opt, i) {
    optsHtml += '<button class="survey-opt" onclick="answerSurvey(' + i + ')">' + opt.text + '</button>';
  });

  container.innerHTML =
    '<div class="progress-bar"><div class="progress-fill" style="width:' + progress + '%">' + progress + '%</div></div>' +
    '<div class="survey-q">' +
      '<h4>Вопрос ' + surveyState.currentQ + ' из ' + surveyQuestions.length + ': ' + q.q + '</h4>' +
      '<div class="survey-options">' + optsHtml + '</div>' +
    '</div>';
}

function startSurvey() {
  var nameInput = document.getElementById('survey-name');
  if (!nameInput || !nameInput.value.trim()) {
    alert('Пожалуйста, введите ФИО');
    return;
  }
  surveyState.name = nameInput.value.trim();
  surveyState.currentQ = 1;
  surveyState.answers = [];
  surveyState.scores = {};
  renderSurvey();
}

function answerSurvey(optIndex) {
  var q = surveyQuestions[surveyState.currentQ - 1];
  var opt = q.options[optIndex];
  surveyState.answers.push(optIndex);
  for (var dir in opt.score) {
    surveyState.scores[dir] = (surveyState.scores[dir] || 0) + opt.score[dir];
  }
  surveyState.currentQ++;
  renderSurvey();
}

function renderSurveyResult() {
  var container = document.getElementById('survey-container');
  if (!container) return;

  // Сортируем направления по баллам
  var sorted = [];
  for (var dir in surveyState.scores) {
    sorted.push({ dir: dir, score: surveyState.scores[dir] });
  }
  sorted.sort(function(a, b) { return b.score - a.score; });

  var maxScore = sorted.length > 0 ? sorted[0].score : 1;

  // Топ-2 направления
  var top1 = sorted.length > 0 ? sorted[0] : null;
  var top2 = sorted.length > 1 ? sorted[1] : null;

  // Темы для топ-1
  var topTopics = topics.filter(function(t) { return t.dir === top1.dir; }).slice(0, 4);

  var topicsHtml = '';
  topTopics.forEach(function(t) {
    topicsHtml += '<p style="margin:6px 0;color:#c0b0d8;">№' + t.id + ' — ' + t.title + '</p>';
  });

  var pct1 = Math.round(top1.score / maxScore * 100);
  var pct2 = top2 ? Math.round(top2.score / maxScore * 100) : 0;

  var html =
    '<div class="result-card">' +
      '<h3>Результат анкетирования</h3>' +
      '<p style="margin:12px 0;color:#c0b0d8;">Ученик: <strong style="color:#d0c0e8;">' + surveyState.name + '</strong></p>' +
      '<div class="result-score">' + pct1 + '%</div>' +
      '<p style="font-size:1.2rem;color:#d0c0e8;margin-bottom:8px;">Рекомендованное направление: ' + top1.dir + '</p>' +
      (top2 ? '<p style="color:#a090c0;">Второе направление: ' + top2.dir + ' (' + pct2 + '%)</p>' : '') +
      '<h3 style="margin-top:20px;">Рекомендованные темы:</h3>' +
      topicsHtml +
    '</div>' +
    '<p style="margin-top:16px;color:#8870a0;">Данные отправлены учителю.</p>';

  container.innerHTML = html;

  // Отправка в Google Форму
  submitToGoogleForm(surveyState.name, top1.dir);
}

