function renderTopics(filter = 'all') {
    const list = document.getElementById('topics-list');
    const detail = document.getElementById('topic-detail');
    detail.style.display = 'none';
    list.style.display = 'block';
    list.innerHTML = '';

    const filtered = filter === 'all' ? topics : topics.filter(t => t.category === filter);

    filtered.forEach(topic => {
        const item = document.createElement('div');
        item.className = 'topic-item';
        item.onclick = () => showTopicDetail(topic.id);
        item.innerHTML = `
            <span class="topic-number">${topic.id}</span>
            <span class="topic-tag tag-${topic.category}">${topic.tag}</span>
            <h3>${topic.title}</h3>
            <p>${topic.description.substring(0, 120)}...</p>
        `;
        list.appendChild(item);
    });
}

function showTopicDetail(topicId) {
    const topic = topics.find(t => t.id === topicId);
    if (!topic) return;

    document.getElementById('topics-list').style.display = 'none';
    document.getElementById('topic-filters').style.display = 'none';

    const detail = document.getElementById('topic-detail');
    detail.style.display = 'block';

    let planRows = topic.plan.map(p =>
        `<tr><td><strong>${p.stage}</strong></td><td>${p.task}</td></tr>`
    ).join('');

    detail.innerHTML = `
        <div class="topic-detail-header">
            <button class="back-btn" onclick="closeTopicDetail()">← К списку тем</button>
            <h2>Тема ${topic.id}: ${topic.title}</h2>
            <span class="topic-tag tag-${topic.category}">${topic.tag}</span>
        </div>
        <div class="topic-description">
            <p>${topic.description}</p>
        </div>
        <h3>План работы</h3>
        <table class="topic-plan-table">
            <thead>
                <tr><th>Срок</th><th>Этап работы</th></tr>
            </thead>
            <tbody>
                ${planRows}
            </tbody>
        </table>
    `;
}

function closeTopicDetail() {
    document.getElementById('topic-detail').style.display = 'none';
    document.getElementById('topics-list').style.display = 'block';
    document.getElementById('topic-filters').style.display = 'flex';
}

function filterTopics(category, btn) {
    document.querySelectorAll('.filter-btn').forEach(b => b.classList.remove('active'));
    btn.classList.add('active');
    renderTopics(category);
}

